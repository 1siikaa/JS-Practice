/*
Scope: 
In Programming, scope defines where a variable is accessible.
Variable can be declared at different levels of scope, such as
  Global Scope
  With in Function (Function Scope) 
  Outer Scope of a function (If used in closures)
  Inner or block scope (If used inside a loop or a if else block or a switch case statement)
*/

/*
Shadowing:
When a variable is declared within a scope that already contains a variable with the same name,
the inner variable shadows the outer variable.
*/

/* 
Shadowing Impact:
When a variable is shadowed, it means the inner variable takes precedence within its scope. Any assignment or modification does not
affect the outer variable, and vice versa.
*/









